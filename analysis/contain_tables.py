#!/usr/bin/env python3
"""Summary of the E12contain confirmatory campaigns (both boots) and paper macros.

Usage: contain_tables.py CAMPAIGN_DIR [CAMPAIGN_DIR ...]
  -> analysis/output/contain_summary.json and analysis/output/contain_meta.tex
"""
import glob
import json
import os
import statistics as st
import sys
from collections import defaultdict

cells = defaultdict(list)
for cd in sys.argv[1:]:
    for f in sorted(glob.glob(os.path.join(cd, "runs", "*", "contain_score.json"))):
        r = json.load(open(f))
        cells[(r["mode"], r["execs"])].append(r)

out = {}
for (mode, k), rs in sorted(cells.items()):
    acct = [all(v["kernel_bytes"] == v["destination_bytes"] for v in r["budget"].values()) for r in rs]
    over = [v["overshoot_bytes"] for r in rs for v in r["budget"].values() if v["overshoot_bytes"] is not None]
    out[f"{mode}-K{k}"] = {
        "runs": len(rs),
        "normal_completed": sum(r["normal_completed"] for r in rs), "normal_calls": sum(r["normal_calls"] for r in rs),
        "normal_p50_ms_median": st.median(r["normal_ok_p50_ms"] for r in rs if r["normal_ok_p50_ms"] is not None),
        "normal_p99_ms_median": st.median(r["normal_ok_p99_ms"] for r in rs if r["normal_ok_p99_ms"] is not None),
        "runaway_bytes_median": st.median(r["runaway_bytes"] for r in rs),
        "runaway_completed_median": st.median(r["runaway_completed"] for r in rs),
        "accounting_exact_runs": sum(acct), "max_overshoot_bytes": max(over) if over else None}
os.makedirs("analysis/output", exist_ok=True)
json.dump(out, open("analysis/output/contain_summary.json", "w"), indent=1)


def g(mode, key):
    return [out[f"{mode}-K{k}"][key] for k in (4, 8)]


def ms(v):
    return f"{v:.0f}"


runs = sum(v["runs"] for v in out.values())
calls = {m: (sum(g(m, "normal_completed")), sum(g(m, "normal_calls"))) for m in ("none", "process", "exec")}
tex = [
    "% generated by analysis/contain_tables.py (E12contain, two boots)",
    f"\\newcommand{{\\CtRuns}}{{{runs}}}",
    f"\\newcommand{{\\CtNoneMs}}{{{'/'.join(ms(x) for x in g('none', 'normal_p50_ms_median'))}}}",
    f"\\newcommand{{\\CtExecMs}}{{{'/'.join(ms(x) for x in g('exec', 'normal_p50_ms_median'))}}}",
    f"\\newcommand{{\\CtProcDone}}{{{calls['process'][0]} of {calls['process'][1]}}}",
    f"\\newcommand{{\\CtExecDone}}{{{calls['exec'][0]} of {calls['exec'][1]}}}",
    f"\\newcommand{{\\CtNoneMB}}{{{st.median(g('none', 'runaway_bytes_median')) / 1e6:.1f}}}",
    f"\\newcommand{{\\CtExecKB}}{{{st.median(g('exec', 'runaway_bytes_median')) / 1e3:.0f}}}",
    f"\\newcommand{{\\CtExactRuns}}{{{sum(v['accounting_exact_runs'] for v in out.values())}/{runs}}}",
]
open("analysis/output/contain_meta.tex", "w").write("\n".join(tex) + "\n")
print(json.dumps(out, indent=1))
print("\n".join(tex))
